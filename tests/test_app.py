def test_activity_listing_reflects_signup_and_unregister(client):
    # Arrange
    activity_name = "Chess Club"
    email = "new.student@mergington.edu"

    # Act
    signup_response = client.post(
        f"/activities/{activity_name}/signup",
        params={"email": email},
    )
    listing_after_signup = client.get("/activities")
    unregister_response = client.delete(
        f"/activities/{activity_name}/signup",
        params={"email": email},
    )
    listing_after_unregister = client.get("/activities")

    # Assert
    assert signup_response.status_code == 200
    assert email in listing_after_signup.json()[activity_name]["participants"]
    assert unregister_response.status_code == 200
    assert email not in listing_after_unregister.json()[activity_name]["participants"]